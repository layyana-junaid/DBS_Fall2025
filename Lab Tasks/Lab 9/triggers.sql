-- prevents delete on employees on saturday or sunday 
create or replace trigger trg_prevent_delete_employees_weekend
before delete on employees
for each row
begin
  if lower(trim(to_char(sysdate, 'fmday', 'nls_date_language=english'))) in ('saturday','sunday') then
    raise_application_error(-20001, 'deletions are not allowed on weekends');
  end if;
end;
/

-- create audit table
create table log_salary_audit (
  id             number generated by default as identity,
  employee_id    number,
  old_salary     number,
  new_salary     number,
  changed_by     varchar2(100),
  changed_at     timestamp,
  comment_text   varchar2(4000)
);

create or replace trigger trg_audit_salary_updates
after update of salary on employees
for each row
declare
  v_user varchar2(100);
begin
  v_user := sys_context('userenv','session_user');
  insert into log_salary_audit(employee_id, old_salary, new_salary, changed_by, changed_at)
  values(:old.employee_id, :old.salary, :new.salary, v_user, systimestamp);
end;
/
