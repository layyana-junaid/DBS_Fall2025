-- audit table to store totals after bulk insert operations
create table sales_total_audit (
  id           number generated by default as identity,
  total_amount number,
  row_count    number,
  created_at   timestamp
);

create or replace trigger trg_sales_compound_total
for insert on sales
compound trigger

  g_total number := 0;
  g_count number := 0;

  before statement is
  begin
    g_total := 0;
    g_count := 0;
  end before statement;

  before each row is
  begin
    -- assume sales has columns quantity and unit_price
    if :new.quantity is not null and :new.unit_price is not null then
      g_total := g_total + (:new.quantity * :new.unit_price);
      g_count := g_count + 1;
    end if;
  end before each row;

  after statement is
  begin
    -- store aggregate result after the bulk insert
    insert into sales_total_audit(total_amount, row_count, created_at)
    values(g_total, g_count, systimestamp);
  end after statement;

end trg_sales_compound_total;
/

-- create log table for DDL events
create table schema_ddl_log (
  id            number generated by default as identity,
  username      varchar2(100),
  event         varchar2(30),
  object_type   varchar2(100),
  object_name   varchar2(400),
  sql_text      clob,
  event_time    timestamp
);

create or replace trigger trg_schema_ddl_audit
after ddl on schema
declare
  v_sql   varchar2(4000);
  v_text  clob;
  i       pls_integer := 1;
begin
  if ora_sysevent in ('create','drop') then
    v_text := null;
    begin
      loop
        v_sql := ora_sql_txt(i);
        exit when v_sql is null;
        v_text := nvl(v_text, '') || v_sql || chr(10);
        i := i + 1;
      end loop;
    exception
      when others then
        null; 
    end;

    insert into schema_ddl_log(username, event, object_type, object_name, sql_text, event_time)
    values(
      sys_context('userenv','session_user'),
      ora_sysevent,
      ora_dict_obj_type,
      ora_dict_obj_name,
      v_text,
      systimestamp
    );
  end if;
end;
/

create or replace trigger trg_prevent_update_shipped_orders
before update on orders
for each row
begin
  if :old.order_status is not null and upper(:old.order_status) = 'SHIPPED' then
    raise_application_error(-20003, 'cannot update an order that is already shipped');
  end if;
end;
/

