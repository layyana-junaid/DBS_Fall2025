SELECT d.DEPT_NAME, AVG(e.SALARY) AS AVG_SALARY
FROM EMPLOYEES e
JOIN DEPARTMENTS d ON e.DEPT_ID = d.DEPT_ID
GROUP BY d.DEPT_ID, d.DEPT_NAME
HAVING AVG(e.SALARY) > 50000;

SELECT e.NAME, e.SALARY, d.DEPT_NAME
FROM EMPLOYEES e
JOIN DEPARTMENTS d ON e.DEPT_ID = d.DEPT_ID
WHERE e.SALARY > (
    SELECT AVG(SALARY) 
    FROM EMPLOYEES 
    WHERE DEPT_ID = e.DEPT_ID
);

SELECT d.DEPT_NAME
FROM DEPARTMENTS d
WHERE NOT EXISTS (
    SELECT 1 
    FROM EMPLOYEES e 
    WHERE e.DEPT_ID = d.DEPT_ID AND e.SALARY < 30000
);

SELECT s.STUD_NAME, c.COURSE_NAME
FROM STUDENTS s
JOIN ENROLLMENT e ON s.STUD_ID = e.STUDENT_ID
