-- Employees table with manager relationship
CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID INT PRIMARY KEY,
    NAME VARCHAR(100),
    SALARY DECIMAL(10,2),
    HIRE_DATE DATE,
    DEPT_ID INT,
    MANAGER_ID INT,
    CITY VARCHAR(50)
);

-- Students table with city
CREATE TABLE STUDENTS (
    STUD_ID INT PRIMARY KEY,
    STUD_NAME VARCHAR(100),
    AGE INT,
    DEPT_ID INT,
    CITY VARCHAR(50)
);

-- Faculty/Teachers table
CREATE TABLE FACULTY (
    FACULTY_ID INT PRIMARY KEY,
    NAME VARCHAR(100),
    SALARY DECIMAL(10,2),
    HIRE_DATE DATE,
    DEPT_ID INT,
    CITY VARCHAR(50)
);

-- Teaches relationship
CREATE TABLE TEACHES (
    FACULTY_ID INT,
    COURSE_ID INT,
    PRIMARY KEY (FACULTY_ID, COURSE_ID)
);

